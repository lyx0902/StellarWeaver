import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('isolated repair, patch export and validation, and same-thread follow-up', async ({ page }) => {
  test.skip(!process.env.SW_WEB_E2E_BASE_URL, 'Requires a G4 Compose deployment and a committed calc fixture')
  test.setTimeout(90_000)
  const token = process.env.STELLARWEAVER_WEB_TOKEN
  if (!token) throw new Error('Provide the local test token')
  const title = 'G4 浏览器修复实验 ' + Date.now()
  await page.goto('/')
  await page.getByLabel('访问令牌').fill(token)
  await page.getByRole('button', { name: '连接', exact: true }).click()
  await expect(page.getByText('新线程从仓库已提交的 HEAD 创建独立工作区。')).toBeVisible()
  await page.getByLabel('运行模式').selectOption('repair')
  const prompt = page.getByLabel('任务说明')
  await prompt.fill(title)
  await page.getByRole('button', { name: '运行修复任务' }).click()
  const originalSession = page.getByTestId('session-id')
  const approval = page.getByRole('region', { name: '待审批操作' })
  for (const hint of ['return a + b + 1', 'unittest', '+    return a + b', 'unittest']) {
    await expect(approval).toContainText(hint)
    await approval.getByRole('button', { name: '批准一次' }).click()
  }
  await expect(page.getByTestId('run-status')).toHaveText('已完成')
  const session = await originalSession.textContent()
  const processToggle = page.getByRole('button', { name: /执行过程 · \d+ 次工具调用/ })
  await expect(processToggle).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByText('离线演示已结束，请查看实际测试结果。')).toBeVisible()
  await processToggle.click()
  await expect(processToggle).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByRole('region', { name: '执行过程' })).toContainText('edit_file')
  await processToggle.click()
  await expect(page.getByTestId('context-usage')).toHaveText(/上下文\s*约 [\d,]+ \/ 100,000/)
  await page.getByRole('button', { name: '查看改动', exact: true }).click()
  await expect(page.getByTestId('verification')).toHaveText('passed')
  const review = page.getByRole('region', { name: '补丁审阅' })
  await review.getByText('calc.py · 1 个改动块').click()
  await review.getByRole('checkbox').check()
  const [patch] = await Promise.all([
    page.waitForEvent('download'), review.getByRole('button', { name: '下载所选 Diff' }).click(),
  ])
  expect(readFileSync((await patch.path())!, 'utf8')).toContain('+    return a + b')
  await review.getByRole('button', { name: '在独立工作区应用所选并验证' }).click()
  await expect(originalSession).not.toHaveText(session!)
  await expect(page.getByTestId('run-status')).toHaveText('已完成')
  await expect(page.getByTestId('verification')).toHaveText('passed')
  await page.getByRole('button', { name: '日志', exact: true }).click()
  await expect(page.getByRole('list', { name: '运行事件' })).toContainText('review.applied')
  await page.getByRole('button', { name: title, exact: true }).click()
  await page.getByLabel('运行模式').selectOption('read-only')
  await prompt.fill('查看原线程的工作区')
  await prompt.press('Enter')
  await expect(page.getByText('查看原线程的工作区', { exact: true })).toBeVisible()
  await expect(page.getByTestId('run-status')).toHaveText('已完成')
  await expect(originalSession).toHaveText(session!)
  await expect(page.getByRole('article', { name: '对话轮次' })).toHaveCount(2)
  await expect(page.getByRole('navigation', { name: '项目与线程' }).getByRole('button', { name: title, exact: true })).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('article', { name: '对话轮次' })).toHaveCount(2)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(prompt).toBeInViewport()
  await page.getByRole('button', { name: '运行详情', exact: true }).click()
  await expect(page.getByRole('complementary', { name: '运行详情' })).toBeInViewport()
  await page.getByRole('button', { name: '关闭运行详情' }).click()
  await page.getByRole('button', { name: '打开线程导航' }).click()
  await expect(page.getByRole('navigation', { name: '项目与线程' })).toBeInViewport()
  await page.keyboard.press('Escape')
  await expect(prompt).toBeInViewport()
})
